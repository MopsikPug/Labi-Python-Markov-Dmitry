    # Размеры матрицы (высота и ширина терминального рисунка)
HEIGHT = 7
WIDTH = 21

# Создаем пустую матрицу, заполненную пробелами
matrix = [[" " for _ in range(WIDTH)] for _ in range(HEIGHT)]

# Центр по горизонтали
center_x = WIDTH // 2

# Заполняем матрицу символами по функции y = sqrt(|x|)
for x in range(WIDTH):
    # Находим относительную координату от центра (от -10 до +10)
    rel_x = x - center_x
    
    # Вычисляем y (коэффициент 1.8 подобран для красивого масштаба)
    y = int(1.8 * (abs(rel_x) ** 0.5))
    
    # Переворачиваем y, так как индексы строк в матрице идут сверху вниз
    row = (HEIGHT - 1) - y
    
    # Проверяем, чтобы координата не вышла за границы матрицы
    if 0 <= row < HEIGHT:
        matrix[row][x] = "█"

# Выводим матрицу в терминал
for row in matrix:
    print("".join(row))


